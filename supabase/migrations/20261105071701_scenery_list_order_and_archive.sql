begin;

alter table public.camera_submissions
  add column position bigint generated by default as identity,
  add column deleted_at timestamptz;
-- 現在の新しい順を維持。以後、新規登録はリスト末尾へ追加する。
with ranked as (
  select id, row_number() over (order by created_at desc, id) as position
  from public.camera_submissions
)
update public.camera_submissions s set position = r.position from ranked r where s.id = r.id;
select setval(pg_get_serial_sequence('public.camera_submissions', 'position'), greatest(coalesce(max(position), 1), 1), true)
from public.camera_submissions;
grant usage on sequence public.camera_submissions_position_seq to authenticated;
grant update (position, deleted_at) on public.camera_submissions to authenticated;
create policy "Owners can order and archive their submissions" on public.camera_submissions
for update to authenticated
using ((select app_private.is_camera_admin()) and created_by = (select auth.uid()))
with check ((select app_private.is_camera_admin()) and created_by = (select auth.uid()));
create index camera_submissions_owner_position_idx on public.camera_submissions (created_by, position, id) where deleted_at is null;

create function public.reorder_camera_submissions(ordered_ids uuid[])
returns void language plpgsql security invoker set search_path = '' as $$
declare active_count bigint;
begin
  if not (select app_private.is_camera_admin()) then raise exception 'Permission required' using errcode = '42501'; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('madotabi-scenery-list', 0));
  select count(*) into active_count from public.camera_submissions where created_by = (select auth.uid()) and deleted_at is null;
  if ordered_ids is null or cardinality(ordered_ids) <> active_count
    or (select count(distinct x) from unnest(ordered_ids) x) <> active_count
    or exists (select 1 from unnest(ordered_ids) x where not exists (
      select 1 from public.camera_submissions s where s.id=x and s.created_by=(select auth.uid()) and s.deleted_at is null
    )) then raise exception 'List changed; reload before reordering' using errcode = '40001'; end if;
  update public.camera_submissions s set position = r.ordinality
  from unnest(ordered_ids) with ordinality as r(id, ordinality)
  where s.id=r.id and s.created_by=(select auth.uid()) and s.deleted_at is null;
end;
$$;
revoke all on function public.reorder_camera_submissions(uuid[]) from public, anon;
grant execute on function public.reorder_camera_submissions(uuid[]) to authenticated;

create function public.set_camera_submission_deleted(submission_id uuid, is_deleted boolean)
returns void language plpgsql security invoker set search_path = '' as $$
begin
  if not (select app_private.is_camera_admin()) then raise exception 'Permission required' using errcode = '42501'; end if;
  if is_deleted is null then raise exception 'State is required' using errcode = '22023'; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('madotabi-scenery-list', 0));
  update public.camera_submissions set position = case when not is_deleted and deleted_at is not null then (
    select coalesce(max(s.position), 0) + 1 from public.camera_submissions s
    where s.created_by=(select auth.uid()) and s.deleted_at is null
  ) else position end, deleted_at = case when is_deleted then now() else null end
  where id = submission_id and created_by = (select auth.uid());
  if not found then raise exception 'Submission not found' using errcode = 'P0002'; end if;
end;
$$;
revoke all on function public.set_camera_submission_deleted(uuid, boolean) from public, anon;
grant execute on function public.set_camera_submission_deleted(uuid, boolean) to authenticated;

commit;
